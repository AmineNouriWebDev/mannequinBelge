// Fonction pour créer un élément de galerie
function createGalleryItem(image) {
    const item = document.createElement('div');
    item.className = `gallery-item ${image.filters.join(' ')} size-${image.size}`;
    
    item.innerHTML = `
        <img src="${image.src}" alt="${image.alt}" loading="lazy" />
        <div class="gallery-overlay">
            <span class="bg-black/80 px-3 py-1 rounded text-sm">${image.filters[0]}</span>
        </div>
    `;
    
    // Ajout de l'événement lightbox
    item.addEventListener('click', function() {
        const lightbox = document.getElementById('lightbox');
        const lightboxImg = document.getElementById('lightbox-img');
        lightboxImg.src = image.src;
        lightboxImg.alt = image.alt;
        lightbox.classList.add('active');
        document.body.style.overflow = 'hidden';
    });
    
    return item;
}

// Fonction pour initialiser la galerie
function initializeGallery() {
    const galleryContainer = document.querySelector('.gallery-container');
    
    // Vider le conteneur existant
    galleryContainer.innerHTML = '';
    
    // Créer et ajouter chaque élément d'image
    galleryImages.forEach(image => {
        try {
            const galleryItem = createGalleryItem(image);
            galleryContainer.appendChild(galleryItem);
        } catch (error) {
            console.error('Erreur lors de la création de l\'image:', image.src, error);
        }
    });
    
    // Réinitialiser Isotope si disponible
    if (window.$ && $.fn.isotope) {
        // Attendre un peu que le DOM soit mis à jour
        setTimeout(() => {
            if ($('.gallery-container').data('isotope')) {
                $('.gallery-container').isotope('reloadItems').isotope('layout');
                // Forcer l'affichage initial en 2025
                $grid.isotope({ filter: '.y2025' });
                $(".filter-btn").removeClass("active");
                $(".filter-btn[data-filter='.y2025']").addClass("active");
            }
        }, 100);
    }
}

// Initialiser la galerie lorsque le DOM est chargé
if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', initializeGallery);
} else {
    initializeGallery();
}

// Exporter pour le débogage
window.galleryImages = galleryImages;
window.initializeGallery = initializeGallery;